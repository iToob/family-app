export const DEFAULT_CHARTER = `# Why we're doing this

Our family runs a small economy. You can earn Points by doing useful work, then spend them, save them or swap them for real money. The aim is to learn how earning, spending and saving actually work, and to have some independence while you do it.

# What you always get, no matter what

These are never for sale and never depend on Points:

- Healthy food and a safe home
- The clothes you need
- School and education costs
- Doctor, dentist and medical care
- Basic hygiene and personal care items
- A way to reach us in an emergency
- Lifts to school, medical appointments, and anything needed for your safety
- Internet you need for school

Being in the economy or not makes no difference to any of this, or to being part of this family.

# What's optional

Extras beyond the basics are privileges you can pay for with Points. Examples: a premium phone plan, extra data, streaming, games, treats, non-essential lifts, outings, and designer or extra clothes. A privilege is always optional. We will never use a "privilege" to charge you for something you actually need.

# How you earn Points

- Points are for real contributions that help the family or other people: jobs on the job board, projects, cooking, garden work, and helping out beyond the basics.
- Looking after yourself (your room, your own mess, going to school) is just part of life and isn't paid.
- You can propose your own jobs. Tell us what you'll do, who it helps and what you think it's worth. We might say yes, offer a different amount, or ask questions.
- Do the job properly. If it isn't up to standard we'll ask you to fix it before paying. We won't move the goalposts. The standard is in the job description.
- You'll never be paid for being affectionate or obedient, and you should never accept work that feels unsafe.

# How spending works

- The marketplace lists what you can buy and the price in Points.
- Some things need a parent's OK. While you wait, the Points are set aside so you can't spend them twice.
- Subscriptions (like a phone upgrade) charge automatically each period. If you don't have enough Points, the extra stops. Nothing else changes, and you never go into debt.

# Cash

- {{rate}}. You can ask to swap Points for cash or a bank transfer.
- Your Points are set aside when you ask, and taken out of your balance when we actually pay you.

# Your Points are yours

- Once Points are properly earned and approved, we won't take them away.
- If we make a genuine mistake, we'll fix it with a correction you can see in your history, with a reason. Nothing is ever secretly changed or deleted.
- Balances can't go below zero.

# Joining, pausing and leaving

- Joining is your choice. You can pause or come back any time without a penalty.
- If you pause, you keep your balance and history.

# Disagreements

If you think something's wrong, like a rejected job, a payment or a charge, use "Ask for a review" in the app. We'll look at it, talk it through and write down what we decided.

# Changing the rules

Mum and Dad run the economy and can update these rules. You'll be told about every change, and for big changes we'll ask you to read and acknowledge the new version. Rule changes never wipe out or devalue Points you've already earned.

*This charter is a family agreement, not a legal contract.*
`;
